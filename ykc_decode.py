def cp56_str(b: bytes) -> str:
    ms = int.from_bytes(b[0:2], "little")
    return (f"20{b[6] & 0x7F:02d}-{b[5] & 0x0F:02d}-{b[4] & 0x1F:02d} "
            f"{b[3] & 0x1F:02d}:{b[2] & 0x3F:02d}:{ms // 1000:02d}")


def fault_names(value: int) -> list[str]:
    return [name for i, name in enumerate(FAULT_BITS) if value & (1 << i)]


def _value(kind, raw: bytes) -> str:
    n = int.from_bytes(raw, "little")
    if isinstance(kind, dict):
        return kind.get(n, f"0x{n:02X}")
    if kind == "bcd":
        return raw.hex()
    if kind == "hex":
        return raw.hex(" ")
    if kind == "gun":
        return raw.hex().lstrip("0") or "0"
    if kind == "u":
        return str(n)
    if kind == "u10":
        return f"{n / 10:g}"
    if kind == "u100":
        return f"{n / 100:g}"
    if kind == "u1e4":
        return f"{n / 1e4:.4f}"
    if kind == "u1e5":
        return f"{n / 1e5:.5f}"
    if kind == "money":
        return f"{n / 100:.2f}"
    if kind == "t50":
        return str(n - 50) if n else "—"
    if kind == "cur":
        return f"{400 - n / 10:g}" if n else "0"
    if kind == "ver":
        return f"v{n / 10:g}"
    if kind == "ascii":
        return raw.rstrip(b"\x00\xff").decode("ascii", "replace")
    if kind == "vinrev":
        return raw[::-1].rstrip(b"\x00").decode("ascii", "replace")
    if kind == "cp56":
        return cp56_str(raw)
    if kind == "slots":
        return " ".join(TARIFF_SLOT[min(x, 3)] for x in raw)
    if kind == "cell":
        return f"{(n & 0x0FFF) / 100:g} В, группа {n >> 12}"
    if kind == "fault":
        return f"0x{n:04X}" + (f" ({', '.join(fault_names(n))})" if n else " (нет)")
    if kind == "stop":
        return f"0x{n:02X} {STOP_REASONS.get(n, '')}".strip()
    return raw.hex(" ")


def _variable(ftype: int, body: bytes) -> list[tuple[str, str]]:
    out = [("*станция", body[0:7].hex())]
    rest = body[7:]
    if ftype == 0x44:
        out.append(("*карт", str(rest[0])))
        for i in range(rest[0]):
            c = rest[1 + i * 16:17 + i * 16]
            out.append((f"карта {i + 1}", f"{c[8:16].hex(' ')} (логический {c[0:8].hex()})"))
    elif ftype in (0x46, 0x48):
        out.append(("*карт", str(rest[0])))
        for i in range(rest[0]):
            out.append((f"карта {i + 1}", rest[1 + i * 8:9 + i * 8].hex(" ")))
    elif ftype == 0x45:
        for i in range(len(rest) // 10):
            c = rest[i * 10:i * 10 + 10]
            out.append((f"*карта {c[0:8].hex()}", "удалена" if c[8] == 1 else f"не удалена (0x{c[9]:02X})"))
    elif ftype == 0x47:
        for i in range(len(rest) // 9):
            c = rest[i * 9:i * 9 + 9]
            out.append((f"*карта {c[0:8].hex()}", "есть" if c[8] == 1 else "нет"))
    return out


def decode(ftype: int, body: bytes) -> tuple[str, list[tuple[str, str]]]:
    try:
        if ftype in (0x44, 0x45, 0x46, 0x47, 0x48):
            fields = _variable(ftype, body)
        else:
            fields, pos = [], 0
            for label, size, kind in SPECS.get(ftype, []):
                if pos + size > len(body):
                    break
                fields.append((label, _value(kind, body[pos:pos + size])))
                pos += size
            if pos < len(body):
                fields.append(("лишние байты", body[pos:].hex(" ")))
    except (IndexError, ValueError) as e:
        fields = [("ошибка разбора", repr(e))]
    parts = []
    for k, v in fields:
        if not k.startswith("*") or k == "*станция":
            continue
        label, _, unit = k[1:].partition(", ")
        parts.append(f"{label} {v} {unit}".strip() if unit else f"{label} {v}")
    return " · ".join(parts), [(k.lstrip("*"), v) for k, v in fields]
